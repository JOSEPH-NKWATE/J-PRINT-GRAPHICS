/*
 * ===== LANGUAGE DETECTION (runs in <head>, before the page paints) =====
 * Priority: ?lang=fr|en in the URL > saved choice > browser language.
 */
(function () {
  var supported = ["en", "fr"];
  var html = document.documentElement;
  var lang = null;

  try {
    var fromUrl = (new URLSearchParams(location.search).get("lang") || "").toLowerCase();
    if (supported.indexOf(fromUrl) > -1) lang = fromUrl;
  } catch (e) {}

  if (!lang) {
    try {
      var saved = localStorage.getItem("nj-lang");
      if (supported.indexOf(saved) > -1) lang = saved;
    } catch (e) {}
  }

  if (!lang) {
    var nav = (navigator.languages && navigator.languages[0]) || navigator.language || "en";
    lang = /^fr/i.test(nav) ? "fr" : "en";
  }

  window.NJ_LANG = lang;
  html.lang = lang;

  // The HTML is written in English. For French, hide the page until the text
  // has been swapped (avoids a flash of English). Safety timeout just in case.
  if (lang !== "en") {
    html.classList.add("i18n-wait");
    setTimeout(function () { html.classList.remove("i18n-wait"); }, 2500);
    var t = window.I18N[lang]["meta.title"];
    if (t) document.title = t;
  }
})();
